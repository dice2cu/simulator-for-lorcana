it('publishes optional results before dependent branches without leaking branch outputs', () => {
    const rules: CardRules = { type: 'Action', effect: { type: 'Sequence', effects: [
        { type: 'Do Then',
            do: { type: 'Optional', effect: { type: 'Move Card', cards: 'Self', to: 'Hand' } },
            then: { type: 'Modify Cards', cards: { result: 'Moved Cards' }, modifier: { gainKeyword: 'Rush' } },
            otherwise: { type: 'Move Card', cards: 'Self', to: 'Deck', position: 'Bottom' },
        },
        { type: 'Draw', player: 'You', amount: { count: { result: 'Moved Cards' } } },
    ] } };
    expect(validateCardRules(rules)).toEqual([]);
    if (rules.effect.type !== 'Sequence') throw new Error('Expected a sequence');
    const dependent = rules.effect.effects[0];
    if (dependent?.type !== 'Do Then') throw new Error('Expected dependent play');
    dependent.otherwise = { type: 'Gain Lore', player: 'You', amount: { result: 'Damage Removed' } };
    expect(validateCardRules(rules).map(issue => issue.path)).toEqual(['effect.effects[0].otherwise.amount.result']);
});

