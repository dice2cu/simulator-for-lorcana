it('rejects use limits on passive created rules, including nested branches', () => {
    const passive: ContinuousRule = { type: 'Modify Cards', cards: 'Self', modifier: { stat: 'Strength', amount: 1 } };
    const entry: ContinuousRule = { type: 'Enter Play', cards: { zone: 'Hand', player: 'You' }, exerted: true };
    const rules: ContinuousRule[] = [passive, { type: 'Together', rules: [] }, { type: 'Together', rules: [entry, passive] },
        { type: 'Conditional', if: { exists: 'Self' }, then: entry, otherwise: passive }];
    for (const rule of rules) {
        expect(validateCardRules({ type: 'Action', effect: { type: 'Create Rule', uses: 1, rule } }).map(issue => issue.path)).toEqual(['effect.uses']);
        expect(validateCardRules({ type: 'Character', abilities: [{ type: 'Static', limit: { perTurn: 1, count: "Uses" }, rule }] })
            .map(issue => issue.path)).toEqual(['abilities[0].limit.perTurn']);
    }
    expect(validateCardRules({ type: 'Action', effect: { type: 'Create Rule', rule: passive } })).toEqual([]);
});

