it('binds Selected Player locally when checking whether a matching opponent exists', () => {
    const valid: CardRules = { type: 'Action', effect: { type: 'Conditional', if: { existsPlayer: {
        from: 'Opponents', where: { value: { count: { zone: 'Hand', player: 'Selected Player' } }, is: { equal: 0 } },
    } }, then: { type: 'Gain Lore', player: 'You', amount: 1 } } };
    expect(validateCardRules(valid)).toEqual([]);
    expect(validateCardRules({ type: 'Action', effect: { type: 'Conditional', if: { existsPlayer: 'Selected Player' },
        then: { type: 'Gain Lore', player: 'You', amount: 1 } } }).map(issue => issue.path))
        .toEqual(['effect.if.existsPlayer']);
});

it('rejects deck rules and duplicate keyword encodings in ability grants', () => {
    for (const ability of [
        { type: 'Deck Construction', maxCopies: 99 },
        { type: 'Keyword', keyword: { name: 'Rush' } },
        { type: 'Keyword', keyword: { name: 'Resist', amount: 2 } },
    ] as const) {
        const rules: CardRules = { type: 'Action', effect: {
            type: 'Modify Cards', cards: 'Self',
            // @ts-expect-error Deliberately exercise invalid grant definitions.
            modifier: { gainAbility: ability },
        } };
        expect(validateCardRules(rules).map(issue => issue.path)).toEqual(['effect.modifier.gainAbility']);
    }
    for (const name of ['Boost', 'Shift'] as const) {
        expect(validateCardRules({ type: 'Action', effect: {
            type: 'Modify Cards', cards: 'Self',
            modifier: { gainAbility: { type: 'Keyword', keyword: { name, cost: [] } } },
        } })).toEqual([]);
    }
});

