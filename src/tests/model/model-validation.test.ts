it('rejects challenge expiration in contexts known to be outside a challenge', () => {
    const change = { type: 'Modify Cards', cards: 'Self', modifier: { stat: 'Strength', amount: 2 },
        duration: { until: 'End Of Challenge' } } as const;
    expect(validateCardRules({ type: 'Character', abilities: [{
        type: 'Triggered', trigger: { event: 'Turn Start', player: 'You' }, effect: change,
    }] }).map(issue => issue.path)).toEqual(['abilities[0].effect.duration.until']);
    expect(validateCardRules({ type: 'Character', abilities: [{
        type: 'Activated', cost: [], effect: change,
    }] }).map(issue => issue.path)).toEqual(['abilities[0].effect.duration.until']);
    expect(validateCardRules({ type: 'Action', effect: {
        type: 'Delay', until: { turnEnd: 'You' }, effect: change,
    } }).map(issue => issue.path)).toEqual(['effect.effect.duration.until']);
});

it('allows challenge expiration during a challenge and defers unknown contexts to execution', () => {
    const change = { type: 'Modify Cards', cards: 'Self', modifier: { stat: 'Strength', amount: 2 },
        duration: { until: 'End Of Challenge' } } as const;
    expect(validateCardRules({ type: 'Character', abilities: [{
        type: 'Triggered', trigger: { event: 'Challenge', attacker: 'Self' }, effect: change,
    }] })).toEqual([]);
    // Actions can be generated by effects during a challenge. Their definition
    // alone cannot establish whether this particular invocation has a challenge.
    expect(validateCardRules({ type: 'Action', effect: change })).toEqual([]);
    expect(validateCardRules({ type: 'Action', effect: { type: 'Create Trigger',
        trigger: { event: 'Challenge' }, effect: change,
    } })).toEqual([]);
});

